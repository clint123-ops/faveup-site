// Builds site/assets/icons.svg, a <symbol> sprite of the Lucide icons the pages use.
// Run after adding an icon name below: `npm run icons`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const LUCIDE_VERSION = '0.460.0';
const names = [
  'arrow-right', 'ban', 'bell', 'bell-ring', 'building-2', 'chart-column-increasing', 'check', 'chevron-down',
  'chevron-left', 'chevron-right', 'circle-check-big', 'circle-help', 'clock', 'clock-alert', 'coffee', 'contact-round',
  'download', 'dumbbell', 'external-link', 'gallery-vertical-end', 'hammer', 'heart', 'layers', 'lock', 'mail',
  'mail-plus', 'map-pin', 'megaphone-off', 'message-square-heart', 'message-square-text', 'newspaper', 'pause', 'phone',
  'play', 'qr-code', 'repeat', 'rotate-ccw', 'scissors', 'send', 'shield-check', 'shopping-bag', 'smartphone',
  'sparkles', 'stamp', 'store', 'tag', 'target', 'traffic-cone', 'trending-up', 'user-round', 'users', 'users-round',
  'volume-2', 'volume-x', 'x', 'zap',
];

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../site/assets/icons.svg');
const symbols = await Promise.all(
  names.map(async (name) => {
    const res = await fetch(`https://cdn.jsdelivr.net/npm/lucide-static@${LUCIDE_VERSION}/icons/${name}.svg`);
    if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
    const inner = (await res.text()).replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    return `<symbol id="${name}" viewBox="0 0 24 24">${inner.replace(/\s*\n\s*/g, '')}</symbol>`;
  }),
);
fs.writeFileSync(
  out,
  `<!-- Lucide icons v${LUCIDE_VERSION} (ISC license), generated by scripts/icons.mjs -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`,
);
console.log(`icons.svg: ${names.length} icons`);
